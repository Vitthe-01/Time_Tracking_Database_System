-- Creates the punch registration with perimeter and network checks and daily summary refresh.
CREATE OR REPLACE PROCEDURE sp_registrar_marcacao_ponto(
    p_employee_id integer,
    p_device_id integer,
    p_punch_type_id integer,
    p_punched_at timestamp,
    p_latitude numeric,
    p_longitude numeric,
    p_ip_address inet
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_employer_id integer;
    v_active boolean;
    v_latitude numeric;
    v_longitude numeric;
    v_radius integer;
    v_network cidr;
    v_time_punch_id integer;
BEGIN
    SELECT e.employer_id, e.active, l.latitude, l.longitude, l.radius_meters, l.allowed_network
      INTO v_employer_id, v_active, v_latitude, v_longitude, v_radius, v_network
      FROM employee e
      JOIN work_location l ON l.work_location_id = e.work_location_id
     WHERE e.employee_id = p_employee_id;

    IF NOT FOUND OR v_active IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Employee not found or inactive';
    END IF;

    IF p_punched_at IS NULL OR p_latitude IS NULL OR p_longitude IS NULL OR p_ip_address IS NULL THEN
        RAISE EXCEPTION 'Punch time, latitude, longitude and IP address are required';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM punch_type WHERE punch_type_id = p_punch_type_id) THEN
        RAISE EXCEPTION 'Invalid punch type';
    END IF;

    IF NOT EXISTS (
        SELECT 1
          FROM device
         WHERE device_id = p_device_id
           AND employer_id = v_employer_id
           AND active
    ) THEN
        RAISE EXCEPTION 'Device is not valid for the employer of the employee';
    END IF;

    INSERT INTO time_punch (
        employer_id, employee_id, device_id, punch_type_id, sequence_number, punched_at,
        latitude, longitude, ip_address, outside_perimeter
    ) VALUES (
        v_employer_id, p_employee_id, p_device_id, p_punch_type_id,
        (SELECT COALESCE(MAX(sequence_number), 0) + 1 FROM time_punch),
        p_punched_at, p_latitude, p_longitude, p_ip_address,
        fn_distance_meters(p_latitude, p_longitude, v_latitude, v_longitude) > v_radius
    )
    RETURNING time_punch_id INTO v_time_punch_id;

    IF NOT (p_ip_address <<= v_network) THEN
        INSERT INTO punch_audit (time_punch_id, employee_id, alert_type, description)
        VALUES (v_time_punch_id, p_employee_id, 'network_divergence',
                'IP address outside the allowed network of the work location');
    END IF;

    PERFORM fn_refresh_daily_summary(p_employee_id, p_punched_at::date);
END;
$$;

-- >>> Procedures_Functions/06_sp_fechar_espelho_ponto_mensal.sql
-- Creates the monthly timesheet closing, summing the daily summary of a finished month.
CREATE OR REPLACE PROCEDURE sp_fechar_espelho_ponto_mensal(
    p_employee_id integer,
    p_year integer,
    p_month integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_start_date date;
    v_end_date date;
    v_current_status varchar;
    v_days integer;
    v_worked integer;
    v_overtime integer;
    v_night integer;
    v_absence integer;
BEGIN
    IF p_year IS NULL OR p_month IS NULL OR p_month NOT BETWEEN 1 AND 12 THEN
        RAISE EXCEPTION 'Invalid year or month';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM employee WHERE employee_id = p_employee_id) THEN
        RAISE EXCEPTION 'Employee not found';
    END IF;

    v_start_date := make_date(p_year, p_month, 1);
    v_end_date := (v_start_date + INTERVAL '1 month')::date - 1;

    IF v_end_date >= CURRENT_DATE THEN
        RAISE EXCEPTION 'The month has not ended yet';
    END IF;

    SELECT s.name
      INTO v_current_status
      FROM timesheet t
      JOIN timesheet_status s ON s.timesheet_status_id = t.timesheet_status_id
     WHERE t.employee_id = p_employee_id
       AND t.start_date = v_start_date;

    IF v_current_status = 'Closed' THEN
        RAISE EXCEPTION 'The timesheet for the period is already closed';
    END IF;

    SELECT COUNT(*),
           COALESCE(SUM(worked_minutes), 0),
           COALESCE(SUM(overtime_minutes), 0),
           COALESCE(SUM(night_minutes), 0),
           COALESCE(SUM(CASE WHEN absent THEN scheduled_minutes ELSE 0 END), 0)
      INTO v_days, v_worked, v_overtime, v_night, v_absence
      FROM daily_summary
     WHERE employee_id = p_employee_id
       AND work_date BETWEEN v_start_date AND v_end_date;

    IF v_days = 0 THEN
        RAISE EXCEPTION 'No daily summary found for the period';
    END IF;

    INSERT INTO timesheet (
        employee_id, timesheet_status_id, start_date, end_date, worked_minutes, overtime_minutes,
        night_minutes, absence_minutes, legal_deadline, closed_at, signed_at
    ) VALUES (
        p_employee_id,
        (SELECT timesheet_status_id FROM timesheet_status WHERE name = 'Closed'),
        v_start_date, v_end_date, v_worked, v_overtime, v_night, v_absence,
        (v_start_date + INTERVAL '1 month 4 days')::date,
        CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
    )
    ON CONFLICT (employee_id, start_date) DO UPDATE
       SET timesheet_status_id = EXCLUDED.timesheet_status_id,
           worked_minutes = EXCLUDED.worked_minutes,
           overtime_minutes = EXCLUDED.overtime_minutes,
           night_minutes = EXCLUDED.night_minutes,
           absence_minutes = EXCLUDED.absence_minutes,
           legal_deadline = EXCLUDED.legal_deadline,
           closed_at = EXCLUDED.closed_at,
           signed_at = EXCLUDED.signed_at;
END;
$$;

-- >>> Procedures_Functions/07_sp_abonar_falta_atraso.sql
-- Creates the waiver of absences and lateness, adjusting the daily summary and open timesheets.
CREATE OR REPLACE PROCEDURE sp_abonar_falta_atraso(
    p_employee_id integer,
    p_start_date date,
    p_end_date date,
    p_waiver_type_id integer,
    p_document varchar,
    p_responsible_user varchar,
    p_description varchar
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_waived_minutes integer;
BEGIN
    IF p_document IS NULL OR btrim(p_document) = '' THEN
        RAISE EXCEPTION 'Supporting document is required';
    END IF;

    IF p_responsible_user IS NULL OR btrim(p_responsible_user) = '' THEN
        RAISE EXCEPTION 'Responsible user is required';
    END IF;

    IF p_start_date IS NULL OR p_end_date IS NULL OR p_end_date < p_start_date THEN
        RAISE EXCEPTION 'Invalid waiver period';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM employee WHERE employee_id = p_employee_id AND active) THEN
        RAISE EXCEPTION 'Employee not found or inactive';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM waiver_type WHERE waiver_type_id = p_waiver_type_id) THEN
        RAISE EXCEPTION 'Invalid waiver type';
    END IF;

    IF EXISTS (
        SELECT 1
          FROM timesheet t
          JOIN timesheet_status s ON s.timesheet_status_id = t.timesheet_status_id
         WHERE t.employee_id = p_employee_id
           AND s.name = 'Closed'
           AND t.signed_at IS NOT NULL
           AND t.start_date <= p_end_date
           AND t.end_date >= p_start_date
    ) THEN
        RAISE EXCEPTION 'Period is blocked by a closed and signed timesheet';
    END IF;

    SELECT COALESCE(SUM(CASE WHEN absent THEN scheduled_minutes ELSE late_minutes END), 0)
      INTO v_waived_minutes
      FROM daily_summary
     WHERE employee_id = p_employee_id
       AND work_date BETWEEN p_start_date AND p_end_date
       AND (absent OR late_minutes > 0);

    INSERT INTO absence_waiver (
        employee_id, waiver_type_id, record_status_id, start_date, end_date,
        document, waived_minutes, responsible_user, description
    ) VALUES (
        p_employee_id, p_waiver_type_id,
        (SELECT record_status_id FROM record_status WHERE name = 'Approved'),
        p_start_date, p_end_date, p_document, v_waived_minutes, p_responsible_user, p_description
    );

    UPDATE daily_summary
       SET scheduled_minutes = CASE WHEN absent THEN 0 ELSE scheduled_minutes - late_minutes END,
           absent = FALSE,
           late_minutes = 0
     WHERE employee_id = p_employee_id
       AND work_date BETWEEN p_start_date AND p_end_date
       AND (absent OR late_minutes > 0);

    UPDATE timesheet t
       SET (worked_minutes, overtime_minutes, night_minutes, absence_minutes) = (
           SELECT COALESCE(SUM(d.worked_minutes), 0),
                  COALESCE(SUM(d.overtime_minutes), 0),
                  COALESCE(SUM(d.night_minutes), 0),
                  COALESCE(SUM(CASE WHEN d.absent THEN d.scheduled_minutes ELSE 0 END), 0)
             FROM daily_summary d
            WHERE d.employee_id = t.employee_id
              AND d.work_date BETWEEN t.start_date AND t.end_date
       )
      FROM timesheet_status s
     WHERE s.timesheet_status_id = t.timesheet_status_id
       AND s.name <> 'Closed'
       AND t.employee_id = p_employee_id
       AND t.start_date <= p_end_date
       AND t.end_date >= p_start_date;
END;
$$;

-- >>> Procedures_Functions/08_sp_vincular_escala_trabalho.sql
-- Creates the link of a work schedule to a group of employees, closing their current history.
CREATE OR REPLACE PROCEDURE sp_vincular_escala_trabalho(
    p_work_schedule_id integer,
    p_employee_ids integer[],
    p_start_date date
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_employer_id integer;
BEGIN
    SELECT employer_id INTO v_employer_id
      FROM work_schedule
     WHERE work_schedule_id = p_work_schedule_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Work schedule not found';
    END IF;

    IF p_employee_ids IS NULL OR cardinality(p_employee_ids) = 0 THEN
        RAISE EXCEPTION 'At least one employee is required';
    END IF;

    IF p_start_date IS NULL THEN
        RAISE EXCEPTION 'Start date is required';
    END IF;

    IF EXISTS (
        SELECT 1
          FROM unnest(p_employee_ids) AS informed(employee_id)
         WHERE NOT EXISTS (SELECT 1 FROM employee e WHERE e.employee_id = informed.employee_id)
    ) THEN
        RAISE EXCEPTION 'Some informed employees do not exist';
    END IF;

    IF EXISTS (
        SELECT 1
          FROM employee
         WHERE employee_id = ANY (p_employee_ids)
           AND employer_id <> v_employer_id
    ) THEN
        RAISE EXCEPTION 'Employee does not belong to the employer of the work schedule';
    END IF;

    IF EXISTS (
        SELECT 1
          FROM employee_schedule_history h
         WHERE h.employee_id = ANY (p_employee_ids)
           AND h.work_schedule_id = p_work_schedule_id
           AND p_start_date BETWEEN h.start_date AND COALESCE(h.end_date, DATE 'infinity')
    ) THEN
        RAISE EXCEPTION 'Employee already linked to this work schedule';
    END IF;

    IF EXISTS (
        SELECT 1
          FROM employee_schedule_history h
         WHERE h.employee_id = ANY (p_employee_ids)
           AND daterange(h.start_date, h.end_date, '[]') && daterange(p_start_date, NULL)
           AND NOT (h.end_date IS NULL AND h.start_date < p_start_date)
    ) THEN
        RAISE EXCEPTION 'Work schedule conflicts with the schedule history';
    END IF;

    UPDATE employee_schedule_history
       SET end_date = p_start_date - 1
     WHERE employee_id = ANY (p_employee_ids)
       AND end_date IS NULL;

    INSERT INTO employee_schedule_history (employee_id, work_schedule_id, start_date)
    SELECT DISTINCT informed.employee_id, p_work_schedule_id, p_start_date
      FROM unnest(p_employee_ids) AS informed(employee_id);
END;
$$;

-- >>> Procedures_Functions/09_fn_tg_validate_min_interval.sql
-- Creates the trigger function that rejects punches less than 5 minutes apart.
CREATE OR REPLACE FUNCTION fn_tg_validate_min_interval()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
          FROM time_punch p
         WHERE p.employee_id = NEW.employee_id
           AND p.time_punch_id IS DISTINCT FROM NEW.time_punch_id
           AND p.punched_at > NEW.punched_at - INTERVAL '5 minutes'
           AND p.punched_at < NEW.punched_at + INTERVAL '5 minutes'
    ) THEN
        RAISE EXCEPTION 'Minimum interval of 5 minutes between punches';
    END IF;

    RETURN NEW;
END;
$$;

