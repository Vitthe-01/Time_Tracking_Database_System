-- Creates the daily timesheet detail with punch times, lateness and overtime.
CREATE OR REPLACE VIEW vw_espelho_ponto_detalhado AS
WITH daily_punches AS (
    SELECT p.employee_id,
           p.punched_at::date AS work_date,
           MIN(p.punched_at) FILTER (WHERE t.name = 'Clock In') AS clock_in,
           MIN(p.punched_at) FILTER (WHERE t.name = 'Break Start') AS break_start,
           MIN(p.punched_at) FILTER (WHERE t.name = 'Break End') AS break_end,
           MAX(p.punched_at) FILTER (WHERE t.name = 'Clock Out') AS clock_out
      FROM time_punch p
      JOIN punch_type t ON t.punch_type_id = p.punch_type_id
     GROUP BY p.employee_id, p.punched_at::date
)
SELECT e.employee_id,
       e.name AS employee_name,
       to_char(s.work_date, 'YYYY-MM') AS year_month,
       s.work_date,
       dp.clock_in::time AS clock_in_time,
       dp.break_start::time AS break_start_time,
       dp.break_end::time AS break_end_time,
       dp.clock_out::time AS clock_out_time,
       s.worked_minutes,
       s.late_minutes,
       s.overtime_minutes
  FROM daily_summary s
  JOIN employee e ON e.employee_id = s.employee_id
  LEFT JOIN daily_punches dp ON dp.employee_id = s.employee_id
                            AND dp.work_date = s.work_date;

-- Creates the hour bank balance of active employees by department.
CREATE OR REPLACE VIEW vw_resumo_banco_horas_colaboradores AS
SELECT d.department_id,
       d.name AS department,
       e.employee_id,
       e.name AS employee_name,
       b.balance_minutes,
       ROUND((b.balance_minutes / 60.0)::numeric, 2) AS balance_hours,
       b.updated_at,
       b.expires_at
  FROM hour_bank b
  JOIN employee e ON e.employee_id = b.employee_id
  JOIN department d ON d.department_id = e.department_id
 WHERE e.active;

-- Creates the punch inconsistencies: audit alerts, odd punch counts and insufficient breaks.
CREATE OR REPLACE VIEW vw_relatorio_inconsistencias_ponto AS
SELECT e.employee_id,
       e.name AS employee_name,
       p.punched_at::date AS work_date,
       a.alert_type AS inconsistency_type
  FROM punch_audit a
  JOIN time_punch p ON p.time_punch_id = a.time_punch_id
  JOIN employee e ON e.employee_id = a.employee_id
UNION ALL
SELECT e.employee_id,
       e.name,
       p.punched_at::date,
       'odd_punch_count'
  FROM time_punch p
  JOIN employee e ON e.employee_id = p.employee_id
 GROUP BY e.employee_id, e.name, p.punched_at::date
HAVING COUNT(*) % 2 = 1
UNION ALL
SELECT e.employee_id,
       e.name,
       s.work_date,
       'insufficient_break'
  FROM daily_summary s
  JOIN employee e ON e.employee_id = s.employee_id
 WHERE s.insufficient_break;

-- Creates the monthly night work statement, covering minutes between 22:00 and 05:00.
CREATE OR REPLACE VIEW vw_demonstrativo_adicional_noturno AS
SELECT e.employee_id,
       e.name AS employee_name,
       to_char(s.work_date, 'YYYY-MM') AS year_month,
       SUM(s.night_minutes) AS night_minutes,
       ROUND((SUM(s.night_minutes) / 60.0)::numeric, 2) AS night_hours
  FROM daily_summary s
  JOIN employee e ON e.employee_id = s.employee_id
 WHERE s.night_minutes > 0
 GROUP BY e.employee_id, e.name, to_char(s.work_date, 'YYYY-MM');

-- Creates the work schedule in force for each active employee, with working hours and days off.
CREATE OR REPLACE VIEW vw_escalas_jornadas_vigentes AS
SELECT e.employee_id,
       e.name AS employee_name,
       s.work_schedule_id,
       s.name AS schedule_name,
       s.daily_minutes,
       MIN(d.entry_time) AS entry_time,
       MIN(d.break_start_time) AS break_start_time,
       MIN(d.break_end_time) AS break_end_time,
       MAX(d.exit_time) AS exit_time,
       string_agg(
           (ARRAY['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'])[d.weekday + 1],
           ', ' ORDER BY d.weekday
       ) FILTER (WHERE d.day_off) AS days_off
  FROM employee e
  JOIN employee_schedule_history h ON h.employee_id = e.employee_id
                                  AND h.start_date <= CURRENT_DATE
                                  AND (h.end_date IS NULL OR h.end_date >= CURRENT_DATE)
  JOIN work_schedule s ON s.work_schedule_id = h.work_schedule_id
  JOIN work_schedule_day d ON d.work_schedule_id = s.work_schedule_id
 WHERE e.active
 GROUP BY e.employee_id, e.name, s.work_schedule_id, s.name, s.daily_minutes;

