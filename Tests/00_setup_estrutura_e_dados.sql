    break_start_time time,
    break_end_time time,
    exit_time time,
    CONSTRAINT pk_work_schedule_day PRIMARY KEY (work_schedule_day_id),
    CONSTRAINT uq_work_schedule_day UNIQUE (work_schedule_id, weekday),
    CONSTRAINT fk_work_schedule_day_work_schedule FOREIGN KEY (work_schedule_id) REFERENCES work_schedule (work_schedule_id) ON DELETE CASCADE
