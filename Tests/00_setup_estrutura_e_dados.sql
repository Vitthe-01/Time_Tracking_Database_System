-- Creates the trigger function that audits punches made outside the work location radius.
CREATE OR REPLACE FUNCTION fn_tg_alert_geolocation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
          FROM employee e
          JOIN work_location l ON l.work_location_id = e.work_location_id
         WHERE e.employee_id = NEW.employee_id
           AND fn_distance_meters(NEW.latitude, NEW.longitude, l.latitude, l.longitude) > l.radius_meters
    ) AND NOT EXISTS (
        SELECT 1
          FROM punch_audit
         WHERE time_punch_id = NEW.time_punch_id
           AND alert_type = 'geolocation_divergence'
    ) THEN
        INSERT INTO punch_audit (time_punch_id, employee_id, alert_type, description)
        VALUES (NEW.time_punch_id, NEW.employee_id, 'geolocation_divergence',
                'Coordinates outside the allowed radius of the work location');
    END IF;

    RETURN NEW;
END;
$$;

-- >>> Procedures_Functions/11_fn_tg_block_closed_timesheet.sql
-- Creates the trigger function that blocks punch changes inside a closed and signed timesheet.
CREATE OR REPLACE FUNCTION fn_tg_block_closed_timesheet()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_employee_id integer;
    v_date date;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_employee_id := OLD.employee_id;
        v_date := OLD.punched_at::date;
    ELSE
        v_employee_id := NEW.employee_id;
        v_date := NEW.punched_at::date;
    END IF;

    IF EXISTS (
        SELECT 1
          FROM timesheet t
          JOIN timesheet_status s ON s.timesheet_status_id = t.timesheet_status_id
         WHERE t.employee_id = v_employee_id
           AND s.name = 'Closed'
           AND t.signed_at IS NOT NULL
           AND v_date BETWEEN t.start_date AND t.end_date
    ) THEN
        RAISE EXCEPTION 'Timesheet is closed and signed';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

