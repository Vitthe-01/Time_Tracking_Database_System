-- Creates the haversine distance in meters between two coordinates.
CREATE OR REPLACE FUNCTION fn_distance_meters(
    p_latitude_1 numeric,
    p_longitude_1 numeric,
    p_latitude_2 numeric,
    p_longitude_2 numeric
)
RETURNS numeric
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT ROUND((
        6371000 * 2 * asin(least(1.0, sqrt(
            power(sin(radians((p_latitude_2 - p_latitude_1)::float8 / 2)), 2)
            + cos(radians(p_latitude_1::float8)) * cos(radians(p_latitude_2::float8))
                * power(sin(radians((p_longitude_2 - p_longitude_1)::float8 / 2)), 2)
        )))
    )::numeric, 2);
$$;

-- >>> Procedures_Functions/02_fn_night_minutes.sql
-- Creates the count of minutes worked between 22:00 and 05:00.
CREATE OR REPLACE FUNCTION fn_night_minutes(p_start timestamp, p_end timestamp)
RETURNS integer
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT COALESCE(SUM(GREATEST(0, (EXTRACT(EPOCH FROM (
               LEAST(p_end, d + INTERVAL '29 hours') - GREATEST(p_start, d + INTERVAL '22 hours')
           )) / 60)::integer)), 0)::integer
      FROM generate_series((p_start::date - 1)::timestamp, p_end::date::timestamp, INTERVAL '1 day') AS d;
$$;

