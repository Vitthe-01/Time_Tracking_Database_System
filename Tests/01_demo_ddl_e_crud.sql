-- ============================================================================
-- DEMO 01: DDL (DROP IF EXISTS / CREATE TABLE) + CRUD (INSERT, UPDATE, DELETE)
-- ============================================================================

-- 1. DROP TABLE IF EXISTS + CREATE TABLE com PK, FK e CHECK
DROP TABLE IF EXISTS demo_shift_note;

CREATE TABLE demo_shift_note (
    demo_shift_note_id integer GENERATED BY DEFAULT AS IDENTITY,
    employee_id integer NOT NULL,
    severity varchar(15) NOT NULL DEFAULT 'INFO',
    note varchar(200) NOT NULL,
    CONSTRAINT pk_demo_shift_note PRIMARY KEY (demo_shift_note_id),
    CONSTRAINT fk_demo_shift_note_emp FOREIGN KEY (employee_id) REFERENCES employee (employee_id) ON DELETE RESTRICT,
    CONSTRAINT ck_demo_shift_note_sev CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL'))
);

DO $$
DECLARE
    v_id integer;
BEGIN
    -- 2. INSERT + UPDATE + DELETE na tabela criada
    INSERT INTO demo_shift_note (employee_id, severity, note)
    VALUES (21, 'INFO', 'Registro criado na demonstração')
    RETURNING demo_shift_note_id INTO v_id;

    UPDATE demo_shift_note SET severity = 'WARNING', note = 'Registro editado na demonstração' WHERE demo_shift_note_id = v_id;
    RAISE NOTICE '[OK] CREATE TABLE + INSERT + UPDATE executados (id = %).', v_id;

    -- 3. Teste de bloqueio da constraint CHECK
    BEGIN
        INSERT INTO demo_shift_note (employee_id, severity, note) VALUES (21, 'INVALIDO', 'Erro esperado');
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE '[OK] CHECK bloqueou valor inválido: %', SQLERRM;
    END;

    -- 4. Teste de integridade referencial (ON DELETE RESTRICT)
    BEGIN
        DELETE FROM employer WHERE employer_id = 1;
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE '[OK] ON DELETE RESTRICT protegeu employer #1: %', SQLERRM;
    END;

    DELETE FROM demo_shift_note WHERE demo_shift_note_id = v_id;
    RAISE NOTICE '[OK] DELETE executado com sucesso.';
END $$;

-- 5. Limpeza final
DROP TABLE IF EXISTS demo_shift_note;

SELECT 'DDL + CRUD' AS bloco, 'OK - CREATE, INSERT, UPDATE, CHECK, RESTRICT, DELETE e DROP validados' AS status;
