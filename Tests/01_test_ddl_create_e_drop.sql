-- ============================================================================
-- TESTE 01: DDL — DROP TABLE IF EXISTS, CREATE TABLE, Constraints e Limpeza
-- Testa:
--   1. DROP TABLE IF EXISTS seguro antes da criação (idempotente)
--   2. CREATE TABLE com PK, FK (employee), NOT NULL, CHECK e DEFAULT
--   3. INSERT válido + validação de rejeição pela constraint CHECK
--   4. DROP TABLE IF EXISTS ao final, deixando o schema limpo
-- ============================================================================

-- 1. Remove a tabela de teste caso já exista (não gera erro se não existir)
DROP TABLE IF EXISTS test_shift_note;

-- 2. Cria uma tabela de demonstração vinculada à tabela oficial employee
CREATE TABLE test_shift_note (
    test_shift_note_id integer GENERATED BY DEFAULT AS IDENTITY,
    employee_id integer NOT NULL,
    severity varchar(15) NOT NULL DEFAULT 'INFO',
    note varchar(200) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_test_shift_note PRIMARY KEY (test_shift_note_id),
    CONSTRAINT fk_test_shift_note_employee FOREIGN KEY (employee_id)
        REFERENCES employee (employee_id) ON DELETE RESTRICT,
    CONSTRAINT ck_test_shift_note_severity CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL'))
);

-- 3. Insere registros válidos e testa a constraint CHECK
DO $$
DECLARE
    v_total integer;
BEGIN
    INSERT INTO test_shift_note (employee_id, severity, note)
    VALUES
        (1,  'INFO',    'Tabela criada e populada com sucesso no Teste 01'),
        (21, 'WARNING', 'Teste de chave estrangeira com Colaborador #21');

    SELECT COUNT(*) INTO v_total FROM test_shift_note;
    RAISE NOTICE '[OK] CREATE TABLE + INSERT: % registro(s) gravado(s) em test_shift_note.', v_total;

    -- Testa rejeição de valor inválido na constraint CHECK
    BEGIN
        INSERT INTO test_shift_note (employee_id, severity, note)
        VALUES (1, 'INVALIDO', 'Deve ser bloqueado pela constraint CHECK');
        RAISE WARNING '[FALHA] Deveria ter bloqueado severity inválido!';
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE '[OK] Constraint CHECK bloqueou valor inválido: %', SQLERRM;
    END;
END $$;

-- 4. Remove a tabela de teste ao final para manter o banco limpo
DROP TABLE IF EXISTS test_shift_note;

-- 5. Confirma que a tabela foi removida com sucesso (deve retornar NULL)
SELECT
    'test_shift_note' AS tabela_testada,
    CASE WHEN to_regclass('public.test_shift_note') IS NULL
         THEN 'OK - Criada, validada e removida com DROP TABLE IF EXISTS'
         ELSE 'ERRO - Tabela ainda existe'
    END AS status_final;
